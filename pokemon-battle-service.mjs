// Server-only adapter. Caller authenticates player IDs; never expose this object over JSON.
import {createRequire} from 'node:module';
import {randomUUID} from 'node:crypto';
import {createTeamBuilder} from './pokemon-teams.mjs';
import {POKEDEX} from './pokemon-data.js';
const {BattleStream,getPlayerStreams,TeamValidator}=createRequire(import.meta.url)('pokemon-showdown');
const eligible=new Set(POKEDEX.map(p=>p.id));
const settle=()=>new Promise(resolve=>setImmediate(resolve));

export async function createPokemonBattle({id=randomUUID(),mode,players,seedKey=randomUUID(),seed,now=Date.now,timeoutMs=120000,onResult=()=>{}}){
 if(!['collection','random'].includes(mode))throw new Error('Invalid mode');
 if(!Array.isArray(players)||players.length!==2||players.some(p=>typeof p.id!=='string'||!p.id)||players[0].id===players[1].id)throw new Error('Two distinct players required');
 if(!Number.isFinite(timeoutMs)||timeoutMs<1000)throw new Error('Invalid timeout');
 const builder=createTeamBuilder();
 const sides=players.map((p,i)=>({id:p.id,side:'p'+(i+1),name:String(p.name||'Jugador').replace(/[\r\n|]/g,' ').slice(0,30),request:null,requestId:0,pending:false,deadline:0,log:[]}));
 const teams=players.map((p,i)=>{
  if(mode==='collection'&&(!Array.isArray(p.species)||p.species.length!==6||p.species.some(id=>!eligible.has(id))))throw new Error('Choose six eligible species');
  const team=mode==='random'?builder.buildRandomTeam(seedKey+':'+i):builder.buildCollectionTeam(p.species,seedKey+':'+i);
  // Random formats reject user-supplied teams in their lobby validator. Here teams
  // are generated by the trusted engine; validate their structure as Custom Game.
  const problems=new TeamValidator(builder.formatFor('collection')).validateTeam(team);
  if(problems?.length)throw new Error('Invalid generated team: '+problems.join('; '));
  return team;
 });
 const engine=new BattleStream();
 const streams=getPlayerStreams(engine);
 let result=null,closed=false,turn=0,failure=null,resultDelivery=Promise.resolve();
 function finish(winnerId,reason){if(result)return;result={battleId:id,mode,winnerId,reason,turn};resultDelivery=Promise.resolve().then(()=>onResult({...result}));resultDelivery.catch(e=>{failure=e;});}
 // Drain unused channels, including omniscient; never store/send those to clients.
 const readers=Object.entries(streams).map(([key,stream])=>(async()=>{
  try{for await(const chunk of stream){const side=sides.find(s=>s.side===key);if(!side)continue;
   for(const line of chunk.split('\n')){
    if(line.startsWith('|request|')){side.request=JSON.parse(line.slice(9));side.requestId++;side.pending=false;side.deadline=now()+timeoutMs;}
    else if(line.startsWith('|error|'))side.pending=false;
    else if(line.startsWith('|turn|'))turn=Number(line.slice(6));
    else if(line.startsWith('|win|'))finish(sides.find(s=>s.side===line.slice(5))?.id||null,'battle');
    else if(line==='|tie|')finish(null,'tie');
    if(!line.startsWith('|request|')){side.log.push(line);if(side.log.length>4000)side.log.shift();}
   }
  }}catch(e){failure=e;}
 })());
 function get(playerId){const s=sides.find(s=>s.id===playerId);if(!s)throw new Error('Not a participant');return s;}
 async function flush(){await settle();await settle();if(failure)throw failure;}
 function snapshot(playerId){const s=get(playerId);return structuredClone({battleId:id,mode,side:s.side,players:sides.map(({id,name,side})=>({id,name,side})),turn,requestId:s.requestId,request:s.request,pending:s.pending,deadline:s.deadline,log:s.log,result,closed});}
 async function close(){if(closed)return;closed=true;await engine.writeEnd();await Promise.all(readers);await resultDelivery;}
 async function resign(playerId,reason='forfeit'){const s=get(playerId);if(result||closed)return snapshot(playerId);finish(sides.find(p=>p!==s).id,reason);await engine.write('>forcewin '+sides.find(p=>p!==s).side);await flush();await close();return snapshot(playerId);}
 const api={id,snapshot,flush,close,
  async choose(playerId,{requestId,choice}={}){
   const s=get(playerId);if(result||closed)throw new Error('Battle ended');
   if(requestId!==s.requestId||s.pending||!s.request||s.request.wait)throw new Error('Stale or unavailable turn');
   // A single choice only. Do not allow engine admin commands or newline injection.
   if(typeof choice!=='string'||choice.length>80||! /^(?:move [1-4](?: terastallize)?|switch [1-6]|team [1-6]{6})$/.test(choice))throw new Error('Invalid choice');
   s.pending=true;const before=s.log.length;await streams[s.side].write(choice);await flush();
   const error=s.log.slice(before).find(x=>x.startsWith('|error|'));if(error)throw new Error(error.slice(7));
   if(result)await close();return snapshot(playerId);
  },
  resign,
  async tick(){if(result||closed)return;const overdue=sides.filter(s=>s.request&&!s.request.wait&&!s.pending&&now()>=s.deadline);if(overdue.length===2){finish(null,'timeout');await engine.write('>forcetie');await flush();await close();}else if(overdue.length)await resign(overdue[0].id,'timeout');},
 };
 try{
  // Internal unique names make winner mapping unambiguous even for equal display names.
  await engine.write('>start '+JSON.stringify({formatid:builder.formatFor(mode),...(seed?{seed}:{}),p1:{name:'p1',team:builder.pack(teams[0])},p2:{name:'p2',team:builder.pack(teams[1])}}));
  await flush();return api;
 }catch(e){await close();throw e;}
}
